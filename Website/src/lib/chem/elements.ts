/** Set view of ELEMENTS for O(1) lookups. */
export const ELEMENT_SET: ReadonlySet<string> = new Set(ELEMENTS);

/** True when `symbol` is exactly one of the 118 element symbols (case-sensitive). */
export function isElement(symbol: string): boolean {
  return ELEMENT_SET.has(symbol);
}
